import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = resolve(fileURLToPath(new URL('..', import.meta.url)));
const repoDir = resolve(webDir, '..');

function readEnvFile(filePath) {
  if (!existsSync(filePath)) return {};
  const entries = {};
  for (const rawLine of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eqIndex = line.indexOf('=');
    if (eqIndex <= 0) continue;
    const key = line.slice(0, eqIndex).trim();
    let value = line.slice(eqIndex + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    entries[key] = value;
  }
  return entries;
}

const fileEnv = {
  ...readEnvFile(resolve(repoDir, '.env')),
  ...readEnvFile(resolve(repoDir, '.env.local')),
  ...readEnvFile(resolve(webDir, '.env')),
  ...readEnvFile(resolve(webDir, '.env.local')),
};

const posthogKey = (process.env.POSTHOG_KEY ?? fileEnv.POSTHOG_KEY ?? '').trim();
const posthogHost = (process.env.POSTHOG_HOST ?? fileEnv.POSTHOG_HOST ?? '').trim();

const targetFile = resolve(webDir, 'src/app/services/posthog.env.generated.ts');
const content = `// Auto-generated by scripts/generate-env.mjs — do not commit.
export const POSTHOG_ENV = {
  key: ${JSON.stringify(posthogKey)},
  host: ${JSON.stringify(posthogHost)},
} as const;
`;

writeFileSync(targetFile, content, 'utf8');
