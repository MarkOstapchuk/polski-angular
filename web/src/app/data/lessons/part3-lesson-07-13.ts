import { Activity, ActivityKind, choice, Lesson, typed } from '../lesson-types';

type MatchEntry = [string, string];

const matchItems = (entries: MatchEntry[]) => {
  const options = entries.map(([, answer]) => answer);
  return entries.map(([prompt, answer], i) => choice(`q${i + 1}`, prompt, answer, options));
};

const classifyItems = (entries: Array<[string, string]>, categories: string[]) =>
  entries.map(([prompt, category], i) => choice(`q${i + 1}`, prompt, category, categories));

const pnItems = (entries: Array<[string, 'P' | 'N']>) =>
  entries.map(([prompt, answer], i) => choice(`q${i + 1}`, prompt, answer, ['P', 'N']));

