import { Activity, ActivityItem, ActivityKind, choice, Lesson, typed } from '../lesson-types';

type MatchEntry = [string, string];
type ClassifyEntry = [string, string];

const lesson = (
  id: number,
  title: string,
  subtitle: string,
  topic: string,
  pages: string,
  color: Lesson['color'],
  activities: Activity[],
): Lesson => ({ id, title, subtitle, topic, pages, color, activities });

const matchItems = (entries: MatchEntry[]): ActivityItem[] => {
  const options = [...new Set(entries.map(([, right]) => right))];
  return entries.map(([left, right], i) => choice(`q${i + 1}`, left, right, options));
};

const classifyItems = (entries: ClassifyEntry[], categories: string[]): ActivityItem[] =>
  entries.map(([prompt, category], i) => choice(`q${i + 1}`, prompt, category, categories));

