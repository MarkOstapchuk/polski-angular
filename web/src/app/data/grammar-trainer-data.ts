import type { Language } from '../i18n/language.service';

export type TrainerCategoryId = 'cases' | 'verbs' | 'numbers';
export type TrainerLevel = 'A1' | 'A2' | 'B1';
export type TrainerInputMode = 'mixed' | 'choice' | 'typed';

export interface TrainerQuestion {
  id: string;
  category: TrainerCategoryId;
  subtag: string;
  level: TrainerLevel;
  mode: 'choice' | 'typed';
  prompt: string;
  accepted: string[];
  options?: string[];
  explanation: Record<Language, string>;
}

function q(
  id: string,
  category: TrainerCategoryId,
  subtag: string,
  level: TrainerLevel,
  mode: 'choice' | 'typed',
  prompt: string,
  accepted: string | string[],
  options: string[] | undefined,
  ru: string,
  pl: string,
  en: string,
): TrainerQuestion {
  return {
    id,
    category,
    subtag,
    level,
    mode,
    prompt,
    accepted: Array.isArray(accepted) ? accepted : [accepted],
    options,
    explanation: { ru, pl, en },
  };
}

