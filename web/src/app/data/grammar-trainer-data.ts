function shuffled<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function buildTrainerSet(
  category: TrainerCategoryId | 'mix',
  level: TrainerLevel | 'all',
  inputMode: TrainerInputMode,
  count = 10,
): TrainerQuestion[] {
  let pool = GRAMMAR_TRAINER_QUESTIONS.filter((item) => {
    if (category !== 'mix' && item.category !== category) return false;
    if (level !== 'all' && item.level !== level) return false;
    if (inputMode === 'choice' && !item.options?.length) return false;
    return true;
  });

  if (pool.length === 0) {
    pool = GRAMMAR_TRAINER_QUESTIONS.filter((item) => category === 'mix' || item.category === category);
  }

  return shuffled(pool)
    .slice(0, count)
    .map((item) => {
      if (inputMode === 'typed') return { ...item, mode: 'typed' };
      if (inputMode === 'choice' && item.options?.length) return { ...item, mode: 'choice' };
      return item;
    });
}
