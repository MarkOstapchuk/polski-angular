#!/usr/bin/env python3
"""Link cropped workbook images (manifest.jsonl) to exercises.

Writes `image_assets` into docs/ + web/public content JSONL and the exercise index,
and regenerates web/src/app/data/workbook-images.ts for the app.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "web/public/assets/workbook/manifest.jsonl"
DOCS = ROOT / "docs/platform-content"

images = {}
for line in MANIFEST.open():
    r = json.loads(line)
    if r.get("file") and isinstance(r.get("exercise_number"), int):
        ex = f"WB-L{r['lesson_id']:02d}-E{r['exercise_number']:02d}"
        images.setdefault(ex, []).append(r)
for ex in images:  # page order, then crop order within the page
    images[ex].sort(key=lambda r: (r["pdf_page"], int(r["file"].rsplit("-", 1)[1].split(".")[0])))


def assets(ex):
    return [{"file": r["file"], "label": r["label"], "description": r["description"], "pdf_page": r["pdf_page"]}
            for r in images.get(ex, [])]


def patch(path: Path):
    if not path.exists():
        return
    out = []
    for line in path.open():
        if not line.strip():
            continue
        r = json.loads(line)
        r["image_assets"] = assets(r["exercise_id"])
        if "prompt" in r and r["image_assets"]:
            r["prompt"]["requires_visual"] = True
        out.append(json.dumps(r, ensure_ascii=False))
    path.write_text("\n".join(out) + "\n")


patch(DOCS / "workbook-exercise-index.jsonl")
for f in DOCS.glob("workbook-lesson*-content.jsonl"):
    patch(f)
    patch(ROOT / "web/public/content" / f.name)

ts = {ex: [{"src": "/" + r["file"], "label": r["label"], "alt": r["description"]} for r in rs]
      for ex, rs in sorted(images.items())}
(ROOT / "web/src/app/data/workbook-images.ts").write_text(
    "// Generated by scripts/link-workbook-images.py — do not edit.\n"
    "export interface WorkbookImage { src: string; label: string; alt: string; }\n\n"
    "export const WORKBOOK_IMAGES: Record<string, WorkbookImage[]> = "
    + json.dumps(ts, ensure_ascii=False, indent=2) + ";\n")
print(f"{len(images)} exercises, {sum(map(len, images.values()))} images")
